def add_to_dict_2(dictionary, phase, key, value, component=None, sub_comp=None):
    """
    Adds an entry to the dictionary. For phase='Input', includes component and subcomponent.
    
    Parameters:
    - dictionary: The main dictionary to update.
    - phase: The phase name (e.g., 'Input', 'Assembly').
    - key: The activity key to add.
    - value: The value associated with the key.
    - component: Optional; the component associated with the activity.
    - subcomponent: Optional; the subcomponent associated with the activity.
    """
    if phase == "Input":
        # Add component and subcomponent levels for 'Input' phase
        if phase not in dictionary:
            dictionary[phase] = {}
        if component not in dictionary[phase]:
            dictionary[phase][component] = {}
        if sub_comp not in dictionary[phase][component]:
            dictionary[phase][component][sub_comp] = {}
        dictionary[phase][component][sub_comp][key] = value
    else:
        # Only add the phase and key-value pair for other phases
        if phase not in dictionary:
            dictionary[phase] = {}
        dictionary[phase][key] = value


def find_values_sum(nested_dict, target_key):
    total = 0  # Initialize total sum
    
    def recurse(d):
        nonlocal total
        if isinstance(d, dict):
            for key, value in d.items():
                if key == target_key:
                    total += value  # Add the matching value to the total
                recurse(value)
        elif isinstance(d, list):
            for item in d:
                recurse(item)

    recurse(nested_dict)
    return total

def find_values_sum_multiple(nested_dict, target_keys):
    total = 0  # Initialize total sum
    
    def recurse(d):
        nonlocal total
        if isinstance(d, dict):
            for key, value in d.items():
                if key in target_keys:
                    total += value  # Add the matching value to the total
                recurse(value)
        elif isinstance(d, list):
            for item in d:
                recurse(item)

    recurse(nested_dict)
    return total

def update_dataset_in_dict(dict_activities, phase, old_key, new_key):
    """
    Fetch a dataset from the dictionary, get its value, delete the original dataset, 
    and add a new dataset with the same value.
    
    Parameters:
    - dict_activities (dict): The nested dictionary to modify.
    - phase (str): The phase in the dictionary (e.g., 'Input').
    - old_key (tuple): The key of the dataset to fetch and delete.
    - new_key (tuple): The key of the new dataset to add.
    """
    # Step 1: Fetch the value of the old dataset
    value = find_values_sum(dict_activities, [old_key])
    
    # Step 2: Delete the old dataset
    for component, sub_components in dict_activities[phase].items():
        for sub_comp, datasets in sub_components.items():
            if old_key in datasets:
                del datasets[old_key]
                break  # Exit once the key is deleted
    
    # Step 3: Add the new dataset with the fetched value
    add_to_dict_2(dict_activities, phase, key=new_key, value=value)

##Scaling model: Rotor diameter (m) - Rated power (kW)
def func_rotor_power(x, a, b, c, d):
    y = a - b*np.exp(-(x-d)/c)
    return y

#Scaling model: Hub height (m) - Rated power (kW)
def func_height_power(x, a, b, c):
    y = a - b*np.exp(-(x)/c)
    return y

#Scaling model: Nacelle weight (kg) - Rated power (kW)
def func_nacelle_weight_power(x, a, b):
    y = a * x**2 + b*x
    return 1e3 * y

#Scaling model: Rotor weight (kg) - Rotor diameter (m)
def func_rotor_weight_rotor_diameter(x, a, b):
    y = a * x**2 + b*x
    return 1e3 * y

#Scaling model: Tower (kg) - D²*h (m**3)
def func_tower_weight_d2h(d, h, a, b):
    y = a * d**2*h + b
    return 1e3 * y

