def calculate_minimum_aggregated_distances(lon, lat):
    enercon = pd.read_excel(_DATA_DIR / 'Manufacturing_location_20_largest_EU_manufacturer.xlsx', sheet_name='ENERCON')
    vestas = pd.read_excel(_DATA_DIR / 'Manufacturing_location_20_largest_EU_manufacturer.xlsx', sheet_name='VESTAS')
    # Internal function to calculate aggregated distances for a given dataframe
    def calculate_and_aggregate_distances(df):
        # Function to calculate geodesic distance between given point and each row's point
        def calculate_distance(row):
            return geodesic((row['lat'], row['lon']), (lat, lon)).meters

        # Apply the distance calculation to each row and store in a new column
        df['Distance'] = df.apply(calculate_distance, axis=1)

        # Find the minimum distance per sub-component
        min_distance_df = df.groupby('Sub-component').agg({'Distance': 'min'}).reset_index()

        # Aggregate distances as per instructions
        rotor_distance = min_distance_df[min_distance_df['Sub-component'].isin(['Blades', 'Hub'])]['Distance'].sum()
        nacelle_distance = min_distance_df[min_distance_df['Sub-component'].isin(['Generator', 'Nacelle'])]['Distance'].sum()
        tower_distance = min_distance_df[min_distance_df['Sub-component'] == 'Tower']['Distance'].values[0]
        foundation_distance = 50000  # 50 km for Foundation

        # Calculate the total aggregated distance
        total_distance = rotor_distance + nacelle_distance + tower_distance + foundation_distance

        # Create and return the aggregated distances dataframe and total distance
        aggregated_distances = pd.DataFrame({
            'Component': ['Rotor', 'Nacelle', 'Tower', 'Foundation'],
            'Distance': [rotor_distance, nacelle_distance, tower_distance, foundation_distance]
        })

        return total_distance, aggregated_distances

    # Calculate distances for both dataframes (df and vestas)
    total_distance_df, aggregated_distances_df = calculate_and_aggregate_distances(enercon)
    total_distance_vestas, aggregated_distances_vestas = calculate_and_aggregate_distances(vestas)

    # Compare the total distances and return the dataframe with the minimum total distance
    if total_distance_df < total_distance_vestas:
        return aggregated_distances_df
    else:
        return aggregated_distances_vestas


def transport_requirements(lon, lat, M_nacelle,  M_tower, M_rotor,  M_foundation,  M_all, LT):
    #taken from Vestas 2012 LCA report
    #https://www.vestas.com/~/media/vestas/about/sustainability/pdfs/lca_v903mw_version_1_1.pdf
    trsp_truck=calculate_minimum_aggregated_distances(lon, lat)
    #trsp_truck_nacelle=1025*(M_nacelle/1000)
    trsp_truck_nacelle=trsp_truck.iloc[1,1]/1000*(M_nacelle/1000)
    #trsp_truck_rotor=600*(M_rotor/1000)
    trsp_truck_rotor=trsp_truck.iloc[0,1]/1000*(M_rotor/1000)
    #trsp_truck_tower=1100*(M_tower/1000)
    trsp_truck_tower=trsp_truck.iloc[2,1]/1000*(M_tower/1000)
    trsp_ship_tower=8050*(M_tower/1000)
    #trsp_truck_foundation= 50*(M_foundation/1000)
    trsp_truck_foundation=trsp_truck.iloc[3,1]/1000*(M_foundation/1000)
    
    #transport to local waste facilities
    trsp_end_of_life=200*(M_all/1000)
    
    #30 turbines per plant
    trsp_maintenance_per_year = 2160/30/1000*LT
    
    #600 km by ship assumed
    trsp_ship_offshore = 600*(M_all/1000)
    return trsp_truck_nacelle, trsp_truck_rotor, trsp_truck_tower, trsp_ship_tower,trsp_truck_foundation, trsp_end_of_life, trsp_maintenance_per_year, trsp_ship_offshore


def add_to_dict(dictionary, key, value):
    if key not in dictionary:
         dictionary[key] = value
    else:
         dictionary[key] = dictionary[key] + value


def add_to_nested_dict(dictionary, outer_key, inner_key, value):
    if outer_key not in dictionary:
        dictionary[outer_key] = {}  # Create a nested dictionary for the phase if it doesn't exist

    if inner_key not in dictionary[outer_key]:
        dictionary[outer_key][inner_key] = value  # Add the key-value pair to the nested dictionary
    else:
        dictionary[outer_key][inner_key] += value  # Update the value if the key already exists

